"""Regenerate streamed gameplay coordinates from recovered source transforms."""
import argparse, hashlib, json, math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def prepare():
    source=ROOT/'reports/progression_recovery.json'
    collision=ROOT/'previews/walk/reports/stream_collision.json'
    original=json.loads(source.read_text()); terrain=json.loads(collision.read_text())
    entries={e['component_path_id']:e for s in original['scenes'] if s['scene']=='level3' for e in s['entries']}
    origin=terrain['source_origin']; scale=terrain['physics_scale']
    for name,digest in terrain['source_files_sha256'].items():
        if name in original['source_file_sha256']: assert original['source_file_sha256'][name]==digest
    def position(p):return [round(-(p[0]-origin[0])*scale),round((p[1]-origin[1])*scale),round((p[2]-origin[2])*scale)]
    relics=[entries[i] for i in (6606,6898)]; cp=entries[6752]
    assert all(e['component_enabled'] and e['active_in_serialized_hierarchy'] for e in [*relics,cp])
    assert [r['value'] for r in relics]==[1,16]
    spawn=cp['new_spawn_point']['target']['source_world_position']; camera=cp['new_camera_point']['target']['source_world_position']
    yaw=round(math.atan2(-(camera[0]-spawn[0]),-(camera[2]-spawn[2]))*4096/(2*math.pi))&4095
    report={'source_recovery_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'collision_report_sha256':hashlib.sha256(collision.read_bytes()).hexdigest(),
            'source_origin':origin,'physics_scale':scale,'relics':[{'id':r['component_path_id'],'source_position':r['source_world_position'],'position':position(r['source_world_position']),'value':r['value']} for r in relics],
            'checkpoint':{'id':6752,'spawn':position(spawn),'trigger':position(cp['source_world_position']),'yaw':yaw},
            'limitations':['Two relics only; provisional pickup volume, no original homing/effects','Grounded checkpoint proximity replaces Kiwi interaction','Session state only, no memory-card save']}
    h='/* Generated by prepare_stream_progress.py; physics scale 80, original atlas origin. */\n#define RELIC_COUNT 2\n#define RELIC_TOTAL_VALUE 17\n'
    h+='static const int relic_positions[RELIC_COUNT][3]={'+','.join('{'+','.join(map(str,r['position']))+'}' for r in report['relics'])+'};\nstatic const int relic_values[RELIC_COUNT]={1,16};\n'
    c='/* Original checkpoint 6752; provisional grounded proximity activation. */\nstatic const CheckpointConfig checkpoint_config={'+','.join(map(str,[6752,*position(spawn),yaw,*position(cp['source_world_position'])]))+'};\n'
    return {'src/relic_layout.h':h,'src/checkpoint_config.h':c,'reports/progress_config.json':json.dumps(report,indent=2)+'\n'}
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,content in prepare().items():
        path=ROOT/'previews/walk'/name
        if a.check:assert path.read_text()==content,name
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    print('Streamed relic/checkpoint source coordinates verified' if a.check else 'Streamed relic/checkpoint coordinates generated')
